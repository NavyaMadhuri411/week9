# STEP 2: Import required libraries
import json
import time
from getpass import getpass
from google import genai
from google.genai import errors

# STEP 3: Configure Gemini API
API_KEY = getpass("Enter your Gemini API key: ")
client = genai.Client(api_key=API_KEY)

MODEL = "gemini-3.8-flash"
TEMPERATURE = 0

# ============================================================
# STEP 4: Define initial and refined prompts
# ============================================================

initial_prompt = """
Generate a JSON array describing exactly three books.

Each book must be an object with these three keys:
- "title": string
- "author": string
- "year": integer

Requirements:
1. Use valid JSON syntax.
2. Use double quotes for strings and keys.
3. Do not use trailing commas.
4. Output only the JSON array.
5. Do not include Markdown fences or explanations.

Example of the required structure:
[
  {
    "title": "Example Book",
    "author": "Example Author",
    "year": 2020
  }
]

Generate three books with their correct titles, authors, and
publication years. Return exactly three objects.
"""

refined_prompt = """
Generate exactly three book objects as a JSON array.

Follow this schema strictly:
[
  {
    "title": "Book title",
    "author": "Author name",
    "year": 2000
  }
]

Rules:
- The top-level value must be a JSON array.
- The array must contain exactly three objects.
- Every object must contain exactly these keys:
  "title", "author", "year".
- "title" and "author" must be strings.
- "year" must be an integer.
- Use double quotes for all keys and string values.
- Do not include trailing commas.
- Do not use single-quoted strings.
- Do not include Markdown code fences.
- Do not include explanations or any text outside the JSON.

Return only valid JSON. Nothing else.
"""

# ============================================================
# STEP 5: Generate response with temporary server-error retry
# ============================================================

def generate_with_retry(prompt):
    for attempt in range(4):
        try:
            return client.models.generate_content(
                model=MODEL,
                contents=prompt,
                config={
                    "temperature": TEMPERATURE
                }
            )

        except errors.ServerError:
            if attempt == 3:
                raise

            wait_seconds = 2 ** (attempt + 1)
            print(
                f"Temporary server error. Retrying in "
                f"{wait_seconds} seconds..."
            )
            time.sleep(wait_seconds)


# ============================================================
# STEP 6: Validate JSON and required schema
# ============================================================

REQUIRED_KEYS = {"title", "author", "year"}


def validate_json_response(response_text):
    # Parse JSON; malformed JSON raises JSONDecodeError
    data = json.loads(response_text)

    # Top-level structure must be a list
    if not isinstance(data, list):
        raise ValueError("The JSON top-level value must be an array.")

    # Exactly three book objects are required
    if len(data) != 3:
        raise ValueError("The JSON array must contain exactly 3 books.")

    # Check each object's keys and value types
    for index, book in enumerate(data, start=1):
        if not isinstance(book, dict):
            raise ValueError(f"Book {index} must be a JSON object.")

        if set(book.keys()) != REQUIRED_KEYS:
            raise ValueError(
                f"Book {index} must contain exactly these keys: "
                f"{sorted(REQUIRED_KEYS)}"
            )

        if not isinstance(book["title"], str):
            raise ValueError(f"Book {index}: title must be a string.")

        if not isinstance(book["author"], str):
            raise ValueError(f"Book {index}: author must be a string.")

        # bool is a subclass of int in Python, so exclude it explicitly
        if isinstance(book["year"], bool) or not isinstance(book["year"], int):
            raise ValueError(f"Book {index}: year must be an integer.")

    return data


# ============================================================
# STEP 7: Generate, validate, and retry with refined prompt
# ============================================================

try:
    print("========== INITIAL PROMPT ==========")
    print(initial_prompt)

    first_response = generate_with_retry(initial_prompt)
    first_text = first_response.text or ""

    print("\n========== INITIAL RESPONSE ==========")
    print(first_text if first_text else "No text returned.")

    try:
        books = validate_json_response(first_text)
        print("\nInitial response passed JSON and schema validation.")
        final_text = first_text

    except (json.JSONDecodeError, ValueError) as error:
        print("\n========== INITIAL VALIDATION FAILED ==========")
        print("Validation error:", error)
        print("\nRetrying with the refined prompt...")

        print("\n========== REFINED PROMPT ==========")
        print(refined_prompt)

        second_response = generate_with_retry(refined_prompt)
        second_text = second_response.text or ""

        print("\n========== REFINED RESPONSE ==========")
        print(second_text if second_text else "No text returned.")

        # Validate the refined response
        books = validate_json_response(second_text)
        final_text = second_text

        print("\nRefined response passed JSON and schema validation.")

    # ========================================================
    # STEP 8: Display final validated JSON
    # ========================================================

    print("\n========== FINAL VALIDATED JSON ==========")
    print(json.dumps(books, indent=2, ensure_ascii=False))

    # ========================================================
    # STEP 9: Final validation report
    # ========================================================

    print("\n========== VALIDATION REPORT ==========")
    print("Valid JSON syntax: PASS")
    print("Top-level array: PASS")
    print("Exactly three books: PASS")
    print("Required keys in every object: PASS")
    print("Title and author are strings: PASS")
    print("Year is an integer: PASS")
    print("Temperature used:", TEMPERATURE)
    print("Model used:", MODEL)

except json.JSONDecodeError as error:
    print("\nFINAL FAILURE: The refined response was not valid JSON.")
    print("JSON parsing error:", error)

except ValueError as error:
    print("\nFINAL FAILURE: The refined response failed schema validation.")
    print("Validation error:", error)

except errors.ClientError as error:
    print("\nGemini API request failed.")
    print("Check your API key and model availability.")
    print("Details:", error)

except Exception as error:
    print("\nUnexpected error:", error)

